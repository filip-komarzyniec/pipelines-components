def main() -> int:
    """Main entry point for running component/pipeline tests.

    Returns:
        Exit code (0 for success, non-zero for failure).
    """
    args = parse_args()
    targets = normalize_targets(args.paths)
    test_dirs = discover_test_dirs(targets)  # the broadest folder provided here would be pipelines/ and components/

    if not test_dirs:
        print("No tests/ directories found under the supplied paths. Nothing to do.")
        return 0
    print(test_dirs)

    # relative_dirs = ", ".join(str(directory.relative_to(REPO_ROOT)) for directory in test_dirs)
    print(f"Running pytest for: {test_dirs}")

    # OPTIONS
    # always build image (can be impossible due to some system dependencies)
    # build image when specifically requested (in future change that to build when Konflux jobs run) --> that would require moving all CI/CD to either GH Actions or Konflux

    # tests need to run on the code from PR ---> PR state will be mounted to the container
    # tests need to run on the most recent image (sometimes it can be the one build from the PR)
    # tests need to build the most recent image or wait for Konflux job (not possible)

    image_to_test_dirs = defaultdict(list)
    test_dirs_for_local_execution = []
    for dir in test_dirs:
        # file always exists as required by provided skeletons for components and pipelines folders
        with (dir.parent / "metadata.yaml").open("r", encoding="utf-8") as metadata_file:
            metadata = yaml.safe_load(metadata_file)
        if tests_image := metadata.get("tests", {}).get("image", None):
            image_to_test_dirs[tests_image].append(dir)
        else:
            test_dirs_for_local_execution.append(dir)

    failure = False

    test_reports = []
    if image_to_test_dirs:
        thread_executor = ThreadPoolExecutor(max_workers=6)

        # Does it collect threads -- NO???  --> would async loop not block here????
        for report in thread_executor.map(execute_tests_in_container, image_to_test_dirs.items()):
            test_reports.append(report)

    # run pytest
    report_file = f"report_thread_{threading.get_native_id()}.xml"
    pytest_args = build_pytest_args(
        test_dirs=test_dirs,
        timeout_seconds=TIMEOUT_SECONDS,
        verbose=True,
        junixt_xml_report_file=report_file,
    )
    # -s collect_report

    _ = pytest.main(pytest_args)
    test_reports.append(report_file)

    failure, report = merge_pytest_reports(test_reports)

    print(sub(r"^\s+\b", "", report))

    if failure:
        print("❌ Pytest reported failures. See log above for details.")
        return 1
    print("✅ Pytest completed successfully.")


if __name__ == "__main__":
    sys.exit(main())
